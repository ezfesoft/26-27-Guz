// ---------------------------------------------------------------------------
// Helper: build a week DateTime for semester 2026-2027 Güz
// Semester starts 21 Sep 2026 (Monday);
// 9-15 Nov 2026 is Midterm Exam Week; Week 8 starts 16 Nov 2026.
// ---------------------------------------------------------------------------
DateTime _weekDate(int weekNumber) {
  if (weekNumber <= 7) {
    return DateTime(2026, 9, 21).add(Duration(days: (weekNumber - 1) * 7));
  } else {
    // 9-15 Kasım Sınav Haftası arası; Hafta 8 -> 16 Kasım 2026 Pazartesi başlar
    return DateTime(2026, 11, 16).add(Duration(days: (weekNumber - 8) * 7));
  }
}

